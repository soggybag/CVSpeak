// Glyphs are drawn as text so they are easy to edit: '#' is a lit pixel.
constexpr uint8_t row(const char* s) {
    uint8_t v = 0;
    for (int i = 0; i < 5; ++i) v = static_cast<uint8_t>((v << 1) | (s[i] == '#' ? 1 : 0));
    return v;
}

