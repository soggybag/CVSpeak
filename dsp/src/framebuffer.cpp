constexpr int kNumGlyphs = static_cast<int>(sizeof(kGlyphs) / sizeof(kGlyphs[0]));

// ASCII 32..127 -> glyph index, built at compile time. Missing characters
// (and the '?' fallback) show as a box.
struct GlyphIndex {
    int8_t index[96];
    constexpr GlyphIndex() : index{} {
        for (int i = 0; i < 96; ++i) index[i] = -1;
        for (int g = 0; g < kNumGlyphs; ++g) index[kGlyphs[g].c - 32] = static_cast<int8_t>(g);
    }
};

constexpr GlyphIndex kIndex{};
constexpr uint8_t kBox[7] = {0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f};

const uint8_t* glyphRows(char c) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    const int i = static_cast<unsigned char>(c) - 32;
    if (i < 0 || i >= 96 || kIndex.index[i] < 0) return kBox;
    return kGlyphs[kIndex.index[i]].rows;
}

