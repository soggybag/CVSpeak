void Framebuffer::clear() {
    for (auto& b : data_) b = 0;
}

void Framebuffer::setPixel(int x, int y, bool on) {
    if (x < 0 || x >= kWidth || y < 0 || y >= kHeight) return;
    uint8_t& b = data_[(y / 8) * kWidth + x];
    const uint8_t bit = static_cast<uint8_t>(1u << (y % 8));
    b = on ? static_cast<uint8_t>(b | bit) : static_cast<uint8_t>(b & ~bit);
}

bool Framebuffer::pixel(int x, int y) const {
    if (x < 0 || x >= kWidth || y < 0 || y >= kHeight) return false;
    return (data_[(y / 8) * kWidth + x] >> (y % 8)) & 1u;
}

void Framebuffer::fillRect(int x, int y, int w, int h, bool on) {
    for (int j = y; j < y + h; ++j)
        for (int i = x; i < x + w; ++i) setPixel(i, j, on);
}

void Framebuffer::drawGlyph(int x, int y, char c, int scale, bool on) {
    const uint8_t* rows = glyphRows(c);
    for (int r = 0; r < kGlyphHeight; ++r) {
        for (int col = 0; col < kGlyphWidth; ++col) {
            if (rows[r] & (0x10 >> col)) fillRect(x + col * scale, y + r * scale, scale, scale, on);
        }
    }
}

int Framebuffer::drawText(int x, int y, const char* text, int scale, bool on) {
    int cx = x;
    for (const char* p = text; *p; ++p) {
        drawGlyph(cx, y, *p, scale, on);
        cx += kAdvance * scale;
    }
    return textWidth(text, scale);
}

int Framebuffer::textWidth(const char* text, int scale) {
    int n = 0;
    for (const char* p = text; *p; ++p) ++n;
    if (n == 0) return 0;
    return (n * kAdvance - (kAdvance - kGlyphWidth)) * scale;  // no gap after the last glyph
}

