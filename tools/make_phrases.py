#!/usr/bin/env python3
"""Compile tools/phrases.txt into dsp/src/phrases_generated.cpp.

Each phrase becomes a list of indices into the word bank. The word bank order
is the order of tools/words.txt, so run this after `make words` (which does it
automatically) or whenever phrases.txt changes (`make phrases`).
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORDS = ROOT / "tools" / "words.txt"
PHRASES = ROOT / "tools" / "phrases.txt"
OUT = ROOT / "dsp" / "src" / "phrases_generated.cpp"


def entries(path):
    """Yields (line number, text) for non-blank, non-comment lines."""
    for number, line in enumerate(path.read_text().splitlines(), start=1):
        line = line.strip()
        if line and not line.startswith("#"):
            yield number, line


def main():
    words = [text.upper() for _, text in entries(WORDS)]
    index = {word: i for i, word in enumerate(words)}

    phrases, errors = [], []
    for number, text in entries(PHRASES):
        tokens = text.upper().split()
        missing = [t for t in tokens if t not in index]
        if missing:
            errors.append(f"{PHRASES.name}:{number}: not in words.txt: {', '.join(missing)}")
        elif len(tokens) > 255:
            errors.append(f"{PHRASES.name}:{number}: more than 255 words")
        else:
            phrases.append((" ".join(tokens), [index[t] for t in tokens]))

    if errors:
        print("\n".join(errors), file=sys.stderr)
        print(f"Add the missing words to words.txt and run `make words`.", file=sys.stderr)
        return 1

    out = [
        "// GENERATED by tools/make_phrases.py from tools/phrases.txt (`make phrases`). Do not edit.",
        '#include "cvspeak/word_bank.h"',
        "",
        "namespace cvspeak {",
        "",
        "namespace {",
    ]
    for i, (text, ids) in enumerate(phrases):
        out.append(f"const uint16_t kPhrase{i}[] = {{{', '.join(map(str, ids))}}};  // {text}")
    out += ["", "}  // namespace", "", "const Phrase kPhrases[] = {"]
    for i, (text, ids) in enumerate(phrases):
        out.append(f'    {{"{text}", kPhrase{i}, {len(ids)}}},')
    out += ["};", "", f"const int kNumPhrases = {len(phrases)};", "", "}  // namespace cvspeak", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(phrases)} phrases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
