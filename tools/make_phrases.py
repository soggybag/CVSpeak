#!/usr/bin/env python3
"""Vocabulary and phrase compiler.

The vocabulary is every word in tools/words.txt, in order, followed by any
other words used in tools/phrases.txt (in order of first use). So adding a
phrase is enough: `make words` speaks any new words, then compiles phrases.

  make_phrases.py               write dsp/src/phrases_generated.cpp
  make_phrases.py --vocabulary  print "NAME<TAB>spoken text" per word (for make_words.sh)

words.txt lines are `word` or `word = how to say it`, for words `say`
mispronounces (e.g. `cthulhu = kuh thoo loo`). Punctuation in phrases is ignored.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORDS = ROOT / "tools" / "words.txt"
PHRASES = ROOT / "tools" / "phrases.txt"
WORD_BANK = ROOT / "dsp" / "src" / "words_generated.cpp"
OUT = ROOT / "dsp" / "src" / "phrases_generated.cpp"


def entries(path):
    """Yields (line number, text) for non-blank, non-comment lines."""
    for number, line in enumerate(path.read_text().splitlines(), start=1):
        line = line.strip()
        if line and not line.startswith("#"):
            yield number, line


def normalize(token):
    """Upper-cases a word and drops punctuation (keeps letters, digits, apostrophes)."""
    return re.sub(r"[^A-Z0-9']", "", token.upper())


def phrases():
    """Returns [(line number, [WORD, ...])] for every phrase."""
    result = []
    for number, text in entries(PHRASES):
        tokens = [normalize(t) for t in text.split()]
        result.append((number, [t for t in tokens if t]))
    return result


def vocabulary():
    """Returns [(NAME, spoken text)]: words.txt first, then new phrase words."""
    vocab, seen = [], set()
    for number, text in entries(WORDS):
        name, _, spoken = text.partition("=")
        key = normalize(name.strip())
        if " " in name.strip() or not key:
            sys.exit(f"{WORDS.name}:{number}: one word per line (use `word = spoken text`)")
        if key not in seen:
            vocab.append((key, spoken.strip() or name.strip()))
            seen.add(key)
    for _, tokens in phrases():
        for t in tokens:
            if t not in seen:
                vocab.append((t, t.lower()))
                seen.add(t)
    return vocab


def encoded_words():
    """Names in the current word bank, in index order."""
    if not WORD_BANK.exists():
        return []
    return re.findall(r'^\s*\{"([^"]+)", kWord\d+', WORD_BANK.read_text(), re.MULTILINE)


def main():
    if "--vocabulary" in sys.argv:
        for name, spoken in vocabulary():
            print(f"{name}\t{spoken}")
        return 0

    names = [name for name, _ in vocabulary()]
    if encoded_words() != names:
        new = [n for n in names if n not in set(encoded_words())]
        detail = f" (new: {', '.join(new)})" if new else ""
        print(f"The word bank is out of date{detail}. Run `make words`.", file=sys.stderr)
        return 1
    index = {name: i for i, name in enumerate(names)}

    compiled = []
    for number, tokens in phrases():
        if not tokens:
            continue
        if len(tokens) > 65535:
            sys.exit(f"{PHRASES.name}:{number}: phrase too long")
        compiled.append((" ".join(tokens), [index[t] for t in tokens]))

    out = [
        "// GENERATED by tools/make_phrases.py from tools/phrases.txt (`make phrases`). Do not edit.",
        '#include "cvspeak/word_bank.h"',
        "",
        "namespace cvspeak {",
        "",
        "namespace {",
    ]
    for i, (text, ids) in enumerate(compiled):
        out.append(f"const uint16_t kPhrase{i}[] = {{{', '.join(map(str, ids))}}};  // {text}")
    out += ["", "}  // namespace", "", "const Phrase kPhrases[] = {"]
    for i, (text, ids) in enumerate(compiled):
        out.append(f'    {{"{text}", kPhrase{i}, {len(ids)}}},')
    out += ["};", "", f"const int kNumPhrases = {len(compiled)};", "", "}  // namespace cvspeak", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(compiled)} phrases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
